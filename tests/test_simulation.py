def test_traffic_state_data_structures():
    """Verify TrafficState dataclass initialization, dict conversion, and DQN vector formatting."""
    state = TrafficState(
        simulation_time=15.0,
        step=15,
        total_vehicles=10,
        total_queue=3,
        total_waiting_time=25.5,
        average_speed=8.5,
        current_phase=0,
        current_phase_name="NS_GREEN",
        time_since_phase_change=15.0,
    )

    state.north.queue_length = 2
    state.east.queue_length = 1

    feature_vec = state.to_feature_vector()
    assert isinstance(feature_vec, list)
    assert len(feature_vec) == 6
    assert feature_vec == [2.0, 0.0, 1.0, 0.0, 0.0, 15.0]

    state_dict = state.to_dict()
    assert isinstance(state_dict, dict)
    assert state_dict["total_vehicles"] == 10
    assert state_dict["north"]["queue_length"] == 2


def test_headless_simulation_lifecycle_and_metrics():
    """Execute end-to-end headless SUMO simulation, step physics, collect metrics, and verify cleanup."""
    controller = TraCIController(use_gui=False, step_length=1.0, seed=42)

    try:
        controller.start_simulation()
        assert controller.is_running(), "TraCI controller should be in running state"

        # Advance 30 steps
        for step_idx in range(1, 31):
            state = controller.step_simulation()
            assert isinstance(state, TrafficState)
            assert state.step == step_idx
            assert state.simulation_time == float(step_idx)

        # Query metrics after 30 steps
        metrics = controller.get_metrics()
        assert isinstance(metrics, SimulationMetrics)
        assert metrics.step == 30
        assert metrics.total_vehicles > 0, "Vehicles should have been generated by flow"
        assert metrics.average_speed >= 0.0
        assert metrics.total_queue_length >= 0
        assert "north" in metrics.queues_by_approach
        assert "south" in metrics.queues_by_approach
        assert "east" in metrics.queues_by_approach
        assert "west" in metrics.queues_by_approach

        # Test manual phase switching
        controller.set_tls_phase(2)  # EW_GREEN
        assert controller.get_tls_phase() == 2

        updated_state = controller.step_simulation()
        assert updated_state.current_phase == 2
        assert updated_state.current_phase_name == "EW_GREEN"

    finally:
        controller.close_simulation()
        assert not controller.is_running(), "Controller should not be running after close"


def test_context_manager_cleanup():
    """Verify TraCIController context manager (__enter__ / __exit__) handles cleanup reliably."""
    with TraCIController(use_gui=False) as controller:
        assert controller.is_running()
        controller.step_simulation()

    assert not controller.is_running()


def test_live_vehicle_and_signal_telemetry():
    """Verify TraCIController extracts live individual vehicle spatial states and raw signal state."""
    controller = TraCIController(use_gui=False, step_length=1.0, seed=42)

    try:
        controller.start_simulation()
        # Run enough steps for vehicles to enter intersection
        for _ in range(25):
            state = controller.step_simulation()

        assert isinstance(state, TrafficState)
        assert isinstance(state.signal_raw_state, str)
        assert len(state.signal_raw_state) > 0, "TraCI should return non-empty signal state string"

        assert isinstance(state.vehicles, list)
        if len(state.vehicles) > 0:
            v = state.vehicles[0]
            assert hasattr(v, "id")
            assert hasattr(v, "x")
            assert hasattr(v, "y")
            assert hasattr(v, "angle")
            assert hasattr(v, "speed")
            assert hasattr(v, "lane_id")
            assert hasattr(v, "edge_id")
            assert hasattr(v, "waiting_time")
            assert hasattr(v, "vehicle_type")
            assert 0.0 <= v.x <= 600.0
            assert 0.0 <= v.y <= 600.0
            assert 0.0 <= v.angle <= 360.0
    finally:
        controller.close_simulation()
